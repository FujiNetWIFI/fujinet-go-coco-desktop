def generate_config_h(root: Path, version: str) -> None:
    parts = version.split(".")
    major = parts[0] if parts else "0"
    minor = parts[1] if len(parts) > 1 else "0"
    if not major.isdigit() or not minor.isdigit():
        fail(f"cannot derive RC_REV_* from version {version!r}")
    write(root / "config.h",
          CONFIG_H.format(version=version, major=major, minor=minor))


# --- 2. module registration ------------------------------------------------
#
# XROAR_DESKTOP_MODULES is defined by core/CMakeLists.txt. The Android app
# guards the same edits on __ANDROID__; a define of our own is clearer here,
# because "desktop" covers four different platform macros.

def register_modules(root: Path) -> None:
    patch(root, "src/ui.c", [
        (
            "extern struct ui_module ui_sdl_module;\n",
            "extern struct ui_module ui_sdl_module;\n"
            "extern struct ui_module ui_desktop_module;\n",
        ),
        (
            "\t&ui_null_module,\n\tNULL\n};",
            "#ifdef XROAR_DESKTOP_MODULES\n"
            "\t&ui_desktop_module,\n"
            "#endif\n"
            "\t&ui_null_module,\n\tNULL\n};",
        ),
        # The two native-module list entries WINDOWS32 also gates (see the
        # longer comment on the src/xroar.c patch below for why): without
        # these, a Windows link pulls in extern struct references to
        # filereq_windows32_module/ui_windows32_module, whose defining .c
        # files (src/windows32/...) are never compiled here.
        (
            "#ifdef WINDOWS32\n"
            "\t&filereq_windows32_module,\n"
            "#endif\n",
            "#if defined(WINDOWS32) && !defined(XROAR_DESKTOP_MODULES)\n"
            "\t&filereq_windows32_module,\n"
            "#endif\n",
        ),
        (
            "#ifdef WINDOWS32\n"
            "\t&ui_windows32_module,\n"
            "#endif\n",
            "#if defined(WINDOWS32) && !defined(XROAR_DESKTOP_MODULES)\n"
            "\t&ui_windows32_module,\n"
            "#endif\n",
        ),
    ])

    # src/hkbd.c's OS-native keymap auto-detection is an optional enhancement
    # (falls back to hk_default_update_keymap() otherwise, exactly the path
    # already taken here on Linux and macOS -- neither HAVE_X11 nor
    # HAVE_COCOA is ever defined by generate_config_h either, both being
    # native-GUI-only same as this). hk_windows_update_keymap() is only
    # implemented in src/windows32/hkbd_windows.c, never compiled here.
    patch(root, "src/hkbd.c", [
        (
            "#elif defined(WINDOWS32)\n"
            "\thave_keymap = have_keymap || hk_windows_update_keymap();\n",
            "#elif defined(WINDOWS32) && !defined(XROAR_DESKTOP_MODULES)\n"
            "\thave_keymap = have_keymap || hk_windows_update_keymap();\n",
        ),
    ])

    patch(root, "src/ao.c", [
        (
            "extern struct module ao_null_module;\n",
            "extern struct module ao_null_module;\n"
            "extern struct module ao_desktop_module;\n",
        ),
        (
            "\t&ao_null_module,\n",
            "#ifdef XROAR_DESKTOP_MODULES\n"
            "\t&ao_desktop_module,\n"
            "#endif\n"
            "\t&ao_null_module,\n",
        ),
    ])

    # src/xroar.c's "#ifdef WINDOWS32" blocks are a mix of two different
    # things, and only one of them applies to us:
    #   * genuine POSIX-vs-Windows runtime differences (mkdir()'s signature,
    #     "\\" vs "/" as the path separator, <direct.h>/<shlobj.h>) -- these
    #     are correct as-is and must stay guarded on WINDOWS32 exactly like
    #     upstream, the same as becker.c/hkbd.c/joystick.c/path.c elsewhere
    #     (see generate_config_h for why WINDOWS32 has to stay defined).
    #   * upstream's native win32 GUI module (ui_windows32) and its -C
    #     console-allocation option: the header include (which itself wants
    #     SDL2's sdl2/common.h -- we build SDL3-only), the alloc_console
    #     variable and its two -C/-no-C command-line branches, and the
    #     windows32_init()/windows32_shutdown() calls. Nothing here ever
    #     registers that module -- our own ui_desktop_module stands in for
    #     it, same as every other frontend -- so these need excluding
    #     one at a time (an early attempt tried a single #undef WINDOWS32
    #     right after the includes; that broke the FIRST kind too, since
    #     the mkdir() branch is later in the same file and it is by no
    #     means the only one of that kind).
    patch(root, "src/xroar.c", [
        (
            "#ifdef WINDOWS32\n"
            "#include \"windows32/common_windows32.h\"\n"
            "#endif\n",
            "#if defined(WINDOWS32) && !defined(XROAR_DESKTOP_MODULES)\n"
            "#include \"windows32/common_windows32.h\"\n"
            "#endif\n",
        ),
        (
            "#ifdef WINDOWS32\n"
            "\tint alloc_console = -1;\n"
            "#endif\n",
            "#if defined(WINDOWS32) && !defined(XROAR_DESKTOP_MODULES)\n"
            "\tint alloc_console = -1;\n"
            "#endif\n",
        ),
        (
            "#ifdef WINDOWS32\n"
            "\t\t\t// Windows allocate console option\n"
            "\t\t\talloc_console = 1;\n"
            "#endif\n",
            "#if defined(WINDOWS32) && !defined(XROAR_DESKTOP_MODULES)\n"
            "\t\t\t// Windows allocate console option\n"
            "\t\t\talloc_console = 1;\n"
            "#endif\n",
        ),
        (
            "#ifdef WINDOWS32\n"
            "\t\t\t// Windows allocate console option\n"
            "\t\t\talloc_console = 0;\n"
            "#endif\n",
            "#if defined(WINDOWS32) && !defined(XROAR_DESKTOP_MODULES)\n"
            "\t\t\t// Windows allocate console option\n"
            "\t\t\talloc_console = 0;\n"
            "#endif\n",
        ),
        (
            "#ifdef WINDOWS32\n"
            "\twindows32_init(alloc_console);\n"
            "#endif\n",
            "#if defined(WINDOWS32) && !defined(XROAR_DESKTOP_MODULES)\n"
            "\twindows32_init(alloc_console);\n"
            "#endif\n",
        ),
        (
            "#ifdef WINDOWS32\n"
            "\twindows32_shutdown();\n"
            "#endif\n",
            "#if defined(WINDOWS32) && !defined(XROAR_DESKTOP_MODULES)\n"
            "\twindows32_shutdown();\n"
            "#endif\n",
        ),
    ])


