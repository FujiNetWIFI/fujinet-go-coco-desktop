#!/usr/bin/env python3
"""Transform the staged XRoar tree so it builds headless, as part of our tree.

Run by cmake/StageXRoar.cmake against core/xroar-generated after the copy:

    patch-staged-tree.py <staged-root> <xroar-version>

Two jobs:

  1. Generate `config.h`. XRoar normally gets this from its autotools
     configure; we are not running configure, so we write the headless
     CoCo/Dragon feature set by hand, with the host-dependent half resolved by
     the preprocessor rather than at configure time. One generated file then
     serves Linux, macOS and Windows.

  2. Register our two modules in XRoar's own module lists (src/ui.c, src/ao.c),
     ahead of the null modules. Both transforms are idempotent and hard-fail on
     a missing anchor, so a version bump that moves the anchor text is a build
     error rather than a silently unregistered module.

Everything is written back as UTF-8 with surrogateescape and no newline
translation: Python on Windows otherwise decodes these sources as cp1252 and
rewrites every LF as CRLF on the way out.
"""

import hashlib
import sys
from pathlib import Path


def read(p: Path) -> str:
    return p.read_text(encoding="utf-8", errors="surrogateescape")


def write(p: Path, text: str) -> None:
    with p.open("w", encoding="utf-8", errors="surrogateescape", newline="") as f:
        f.write(text)


def fail(msg: str) -> None:
    sys.exit(f"patch-staged-tree.py: {msg}")


def patch(root: Path, rel: str, transforms) -> None:
    """Apply (anchor, replacement) pairs to root/rel, idempotently.

    The replacement is tested FIRST. Several transforms wrap their anchor
    rather than replacing it, so an anchor-first test re-applies them on a
    second run and nests the result.
    """
    p = root / rel
    if not p.exists():
        fail(f"{rel} not found under {root}")
    text = read(p)
    for anchor, replacement in transforms:
        if replacement in text:
            continue
        if anchor not in text:
            fail(f"anchor not found in {rel}:\n{anchor[:160]}")
        text = text.replace(anchor, replacement, 1)
    write(p, text)


# --- 1. config.h -----------------------------------------------------------
#
# The feature selection (WANT_*) matches the Android app's: the Becker port,
# traps, snapshots, the Dragon and CoCo3 machine architectures, the Dragon cart
# architecture, and the 6801/6809/6821/6847/6883/TCC1014 parts. No SDL, GTK,
# X11, WASM or OpenGL: those frontends are never compiled, and
# core/xroar/desktop/{ui,ao,joystick}_desktop.c stand in for them.

CONFIG_H = r"""/* Generated by tools/xroar/patch-staged-tree.py -- do not edit.
 *
 * Headless XRoar {version} for fujinet-go-coco-desktop: no SDL/GTK/X11/WASM/
 * OpenGL frontend, Becker port enabled, CoCo/Dragon machines only.
 *
 * XRoar's configure is not run, so the host-dependent half of this file is
 * resolved by the preprocessor instead. One file serves Linux, macOS and
 * Windows; keep it that way.
 */
#ifndef XROAR_DESKTOP_CONFIG_H
#define XROAR_DESKTOP_CONFIG_H

#define PACKAGE "xroar"
#define PACKAGE_NAME "XRoar"
#define PACKAGE_TARNAME "xroar"
#define PACKAGE_VERSION "{version}"
#define PACKAGE_STRING "XRoar {version}"
#define PACKAGE_BUGREPORT "xroar@6809.org.uk"
#define PACKAGE_URL "https://www.6809.org.uk/xroar/"
#define PACKAGE_TEXT "XRoar"
#define PACKAGE_YEAR "2026"
#define VERSION "{version}"
#define RC_REV_MAJOR {major}
#define RC_REV_MINOR {minor}

/* Standard headers: C99 plus the POSIX set every host we build for has. */
#define STDC_HEADERS 1
#define HAVE_STDIO_H 1
#define HAVE_STDINT_H 1
#define HAVE_STDLIB_H 1
#define HAVE_STRING_H 1
#define HAVE_INTTYPES_H 1
#define HAVE_SYS_STAT_H 1
#define HAVE_SYS_TYPES_H 1

#if !defined(_WIN32)
#define HAVE_STRINGS_H 1
#define HAVE_UNISTD_H 1
/* popen() drives the printer pipe. MinGW spells it _popen and XRoar does not,
 * so the printer simply has no pipe destination on Windows. */
#define HAVE_POPEN 1
#endif

/* endian.h is a glibc/bionic header. Elsewhere portalib/pl-endian.h falls back
 * to little-endian, which is correct for every host this project targets
 * (x86_64 and arm64); HAVE_BIG_ENDIAN would have to be defined here for a
 * big-endian one. */
#if defined(__linux__)
#define HAVE_ENDIAN_H 1
#endif

/* POSIX regular expressions, used by portalib/sdsx.c to tokenise. MinGW-w64
 * has no regex.h; XRoar's own Windows builds use TRE, and so do ours -- the
 * Windows toolchain must provide libsystre/libtre (see the mingw-w64
 * toolchain file). */
#if defined(_WIN32)
#define HAVE_TRE 1
#else
#define HAVE_REGEX_H 1
#endif

/* portalib supplies its own strsep()/strnlen() when the host lacks them; both
 * are present everywhere we build. */
#define HAVE_STRSEP 1
#define HAVE_STRNLEN 1

#define HAVE_GETADDRINFO 1
#define HAVE_PTHREADS 1

/* Compiler builtins / attributes. GCC and clang both have all of these; MSVC
 * is not a supported compiler for this tree (we cross-compile with MinGW). */
#if defined(__GNUC__)
#define HAVE___BUILTIN_EXPECT 1
#define HAVE___BUILTIN_PARITY 1
#define HAVE_FUNC_ATTRIBUTE_CONST 1
#define HAVE_FUNC_ATTRIBUTE_FORMAT 1
#define HAVE_FUNC_ATTRIBUTE_MALLOC 1
#define HAVE_FUNC_ATTRIBUTE_NONNULL 1
#define HAVE_FUNC_ATTRIBUTE_NORETURN 1
#define HAVE_FUNC_ATTRIBUTE_PURE 1
#define HAVE_FUNC_ATTRIBUTE_RETURNS_NONNULL 1
#define HAVE_VAR_ATTRIBUTE_NONSTRING 1
#define HAVE_VAR_ATTRIBUTE_PACKED 1
#endif

/* Audio: keep the null backend available as a fallback behind ao_desktop. */
#define HAVE_NULL_AUDIO 1

/* Diagnostics. The CPU instruction TRACE is off: it needs the *_trace.c
 * sources, which the debugger builds separately for its own disassembler. */
#define LOGGING 1

#define SIZEOF_FLOAT 4
#define SIZEOF_DOUBLE 8

/* XRoar feature selection. */
#define WANT_BECKER 1
#define WANT_TRAPS 1
#define ENABLE_SNAPSHOT 1
#define WANT_MACHINE_ARCH_DRAGON 1
#define WANT_MACHINE_ARCH_COCO3 1
#define WANT_CART_ARCH_DRAGON 1
#define WANT_PART_MC6801 1
#define WANT_PART_MC6809 1
#define WANT_PART_MC6821 1
#define WANT_PART_MC6847 1
#define WANT_PART_MC6883 1
#define WANT_PART_TCC1014 1

#endif /* XROAR_DESKTOP_CONFIG_H */
"""


def generate_config_h(root: Path, version: str) -> None:
    parts = version.split(".")
    major = parts[0] if parts else "0"
    minor = parts[1] if len(parts) > 1 else "0"
    if not major.isdigit() or not minor.isdigit():
        fail(f"cannot derive RC_REV_* from version {version!r}")
    write(root / "config.h",
          CONFIG_H.format(version=version, major=major, minor=minor))


# --- 2. module registration ------------------------------------------------
#
# XROAR_DESKTOP_MODULES is defined by core/CMakeLists.txt. The Android app
# guards the same edits on __ANDROID__; a define of our own is clearer here,
# because "desktop" covers four different platform macros.

def register_modules(root: Path) -> None:
    patch(root, "src/ui.c", [
        (
            "extern struct ui_module ui_sdl_module;\n",
            "extern struct ui_module ui_sdl_module;\n"
            "extern struct ui_module ui_desktop_module;\n",
        ),
        (
            "\t&ui_null_module,\n\tNULL\n};",
            "#ifdef XROAR_DESKTOP_MODULES\n"
            "\t&ui_desktop_module,\n"
            "#endif\n"
            "\t&ui_null_module,\n\tNULL\n};",
        ),
    ])

    patch(root, "src/ao.c", [
        (
            "extern struct module ao_null_module;\n",
            "extern struct module ao_null_module;\n"
            "extern struct module ao_desktop_module;\n",
        ),
        (
            "\t&ao_null_module,\n",
            "#ifdef XROAR_DESKTOP_MODULES\n"
            "\t&ao_desktop_module,\n"
            "#endif\n"
            "\t&ao_null_module,\n",
        ),
    ])


def main() -> None:
    if len(sys.argv) != 3:
        fail("usage: patch-staged-tree.py <staged-root> <xroar-version>")
    root = Path(sys.argv[1])
    version = sys.argv[2]

    if not (root / "src" / "xroar.c").exists():
        fail(f"{root} does not look like a staged XRoar tree")

    generate_config_h(root, version)
    register_modules(root)

    # Record what the transforms produced, so a human comparing two staged
    # trees can tell whether the difference is upstream's or ours.
    digest = hashlib.sha256()
    for rel in ("config.h", "src/ui.c", "src/ao.c", "src/becker.c"):
        digest.update(read(root / rel).encode("utf-8", "surrogateescape"))
    print(f"XRoar {version} staged; transforms sha256 {digest.hexdigest()[:16]}")


if __name__ == "__main__":
    main()
