#!/usr/bin/env python3
"""Generate a C file embedding the CoCo ROM images into the binaries.

Usage: embed-roms.py <out.c> --system <rom>... --free <rom>...

XRoar resolves machine and cartridge ROMs by *basename* against its -rompath,
so nothing has to be patched into the core: the session materialises whatever
is embedded here into the user's ROM directory on first start and points
-rompath at it. That is also why every ROM keeps its exact filename.

Two classes, and the difference is the whole point:

  --free    HDB-DOS DW3 (hdbdw3bck, hdbdw3bc3). Freely redistributable, and
            the FujiNet link does not work without them, so they are ALWAYS
            embedded.
  --system  Color BASIC (bas13), Extended Color BASIC (extbas11) and the
            CoCo 3 Super Extended Color BASIC (coco3). Tandy/Microware
            copyright and NOT freely licensed. These are embedded only for
            WITH_COCO_ROMS=ON, which is a local-development build that must
            not be redistributed. Every artifact this repository publishes is
            built WITH_COCO_ROMS=OFF, and core/tests/no_embedded_roms.py
            checks that claim against the shipped binaries.

See COMPLIANCE.md.

The generated file lives in the build tree only.
"""

import sys
from pathlib import Path

# Sizes are asserted so a truncated or wrong-variant image is a build error
# rather than a machine that half-boots.
EXPECTED = {
    "bas13": 0x2000,
    "extbas11": 0x2000,
    "coco3": 0x8000,
    "hdbdw3bck": 0x2000,
    "hdbdw3bc3": 0x2000,
}


def emit_array(out, ident: str, data: bytes) -> None:
    out.write(f"static const unsigned char {ident}[] = {{\n")
    for i in range(0, len(data), 16):
        row = ", ".join(f"0x{b:02x}" for b in data[i:i + 16])
        out.write(f"    {row},\n")
    out.write("};\n\n")


def main() -> int:
    args = sys.argv[1:]
    if not args:
        sys.exit(__doc__)

    out_path = Path(args[0])
    system: list[Path] = []
    free: list[Path] = []
    bucket = None
    for a in args[1:]:
        if a == "--system":
            bucket = system
        elif a == "--free":
            bucket = free
        elif bucket is None:
            sys.exit(f"embed-roms.py: {a} before --system/--free")
        else:
            bucket.append(Path(a))

    roms = []
    for path, is_system in [(p, True) for p in system] + [(p, False) for p in free]:
        name = path.stem
        if name not in EXPECTED:
            sys.exit(f"embed-roms.py: unknown ROM {name} ({path})")
        data = path.read_bytes()
        if len(data) != EXPECTED[name]:
            sys.exit(f"embed-roms.py: {path} is {len(data)} bytes, "
                     f"expected {EXPECTED[name]}")
        roms.append((name, data, is_system))

    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8", newline="") as out:
        out.write("/* Generated by tools/xroar/embed-roms.py -- do not edit.\n"
                  " *\n"
                  " * See COMPLIANCE.md before redistributing a binary built\n"
                  " * from this file with the Tandy/Microware system ROMs in it.\n"
                  " */\n\n")
        out.write('#include "roms_embedded.h"\n\n')

        for name, data, _ in roms:
            emit_array(out, f"rom_{name.replace('-', '_')}", data)

        out.write("const coco_embedded_rom coco_embedded_roms[] = {\n")
        for name, data, is_system in roms:
            ident = f"rom_{name.replace('-', '_')}"
            out.write(f'    {{ "{name}.rom", {ident}, sizeof {ident}, '
                      f'{1 if is_system else 0} }},\n')
        out.write("};\n\n")
        out.write(f"const int coco_embedded_rom_count = "
                  f"{len(roms)};\n")
        out.write(f"const int coco_embedded_system_roms = "
                  f"{1 if system else 0};\n")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
